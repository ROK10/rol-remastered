"""Compiles the UI-scale vertex shader variants (uiscale_vs.hlsl) with fxc and writes uiscale_vs.h.

Run after editing the shader:  py -3.14 modkit/native/rolhook/gen_uiscale_vs.py
Needs fxc.exe from the Windows 10 SDK (the vs_2_0 profile).
"""
import glob
import os
import struct
import subprocess
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, 'uiscale_vs.hlsl')
OUT = os.path.join(HERE, 'uiscale_vs.h')


def find_fxc():
    hits = sorted(glob.glob(r'C:\Program Files (x86)\Windows Kits\10\bin\10.*\x86\fxc.exe'))
    if not hits:
        raise SystemExit('fxc.exe not found (install the Windows 10 SDK)')
    return hits[-1]


def main():
    fxc = find_fxc()
    variants = []
    with tempfile.TemporaryDirectory() as tmp:
        for col0 in (0, 1):
            for col1 in (0, 1):
                for tex in range(5):
                    out = os.path.join(tmp, f'v{col0}{col1}{tex}.vso')
                    subprocess.run([fxc, '/nologo', '/T', 'vs_2_0', '/E', 'main', '/O3', f'/DCOL0={col0}',
                                    f'/DCOL1={col1}', f'/DTEX={tex}', '/Fo', out, SRC], check=True,
                                   stdout=subprocess.DEVNULL)
                    data = open(out, 'rb').read()
                    variants.append((col0, col1, tex, struct.unpack(f'<{len(data) // 4}I', data)))
    lines = ['// Generated by gen_uiscale_vs.py from uiscale_vs.hlsl (fxc, vs_2_0) - do not edit.',
             '#pragma once', '']
    for col0, col1, tex, words in variants:
        lines.append(f'static const DWORD kUiVs_{col0}{col1}{tex}[] = {{')
        for i in range(0, len(words), 8):
            lines.append('    ' + ', '.join(f'0x{w:08x}' for w in words[i:i + 8]) + ',')
        lines.append('};')
    lines += ['', 'struct UiVsVariant {', '    int col0, col1, tex;', '    const DWORD* code;', '};',
              'static const UiVsVariant kUiVsVariants[] = {']
    for col0, col1, tex, _ in variants:
        lines.append(f'    {{{col0}, {col1}, {tex}, kUiVs_{col0}{col1}{tex}}},')
    lines += ['};', '']
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines))
    print(f'{len(variants)} variants -> {OUT}')


if __name__ == '__main__':
    main()
